/** 접두어가 행정구역/역 이름으로 끝나면 지역으로 간주 (예: 연희동, 상봉역, 마포구) */
const PLACE_TAIL = /(동|읍|면|구|시|군|역)$/;

/**
 * "지역명 + 카페" 조합인지 판별.
 * - 성수카페 / 대전카페 / 연희동카페 / 상봉역카페 → true (제외)
 * - 브런치카페 / 베이커리카페 / 디저트카페 / 카페 → false (유지)
 */
export function isRegionCafe(keyword: string): boolean {
  const k = keyword.replace(/\s+/g, "");
  if (!k.endsWith("카페")) return false;
  const prefix = k.slice(0, -2);
  if (!prefix) return false; // "카페" 단독은 유지
  if (REGIONS.some((r) => prefix.includes(r))) return true;
  return PLACE_TAIL.test(prefix);
}

export function isNoiseKeyword(keyword: string): boolean {
  const k = keyword.replace(/\s+/g, "");
  if (!k) return true;
  if (isRegionCafe(k)) return true;
  if (NOISE_SUFFIXES.some((s) => k.endsWith(s))) return true;
  return NOISE_SUBSTRINGS.some((s) => k.includes(s));
}

export function filterNoise<T extends { name: string }>(items: T[]): T[] {
  return items.filter((it) => !isNoiseKeyword(it.name));
}
